import { readFileSync, writeFileSync } from "node:fs";
const page = readFileSync(new URL("../index.html", import.meta.url), "utf8");
const script = page.match(/<script[^>]*id="game-script"[^>]*>([\s\S]*?)<\/script>/)?.[1];
if (!script) throw new Error("Game script not found");
const tiers = JSON.parse(script.match(/const levels = (\[[\s\S]*?\n\]);/)[1]);
const constants = ["width", "floor", "line", "left", "right", "spawnY", "step", "clamp", "reviveInterval", "ticketInterval", "finalPairPoints", "dangerSeconds", "rulesVersion", "tickRate", "maxTicks", "maxActions"];
const gameplay = ["dailyPiece", "removePiece", "addScore", "makeBall", "drop", "mergeChain", "clearBoard", "merge", "bound", "collide", "advance", "revive"];
const constant = name => {
  const match = script.match(new RegExp("^const " + name + " = .+;$", "m"));
  if (!match) throw new Error("Missing game constant " + name);
  return match[0];
};
const func = name => {
  const match = script.match(new RegExp("^function " + name + "\\([^\\n]*\\n[\\s\\S]*?^}", "m"));
  if (!match) throw new Error("Missing game function " + name);
  return match[0];
};
const code = `// Generated by daily/build-engine.mjs from the production game's physics.
${constants.map(constant).join("\n")}
const levels = ${JSON.stringify(tiers.map(({radius,points})=>({radius,points})))};
export { rulesVersion, tickRate, maxTicks, maxActions };

export function replay(seed, actions, finalTick) {
  if (!Array.isArray(actions) || actions.length > maxActions || !Number.isInteger(finalTick) || finalTick < 1 || finalTick > maxTicks) return null;
  let draw = 0;
  function randomLevel() { return dailyPiece(seed, draw++, levels.length); }
  let balls = [], particles = [];
  let score = 0, coins = 0, tickets = 0, cooldown = 0, drops = 0, highestLevel = 0, roundTick = 0;
  let state = "playing", aim = width / 2, removalMode = false;
  let shownLevel = randomLevel(), nextLevel = randomLevel();
  const divineLevel = levels.length - 1;
  const cilantroLevel = divineLevel - 1;
  const rank = { open: false }, result = { close() {} }, profile = { best: 0 };
  const nextCanvas = { setAttribute() {} };
  const noOp = () => {};
  const wakeSound = noOp, drawIcon = noOp, updateRemovalControl = noOp, playSound = noOp;
  const burst = noOp, saveProfile = noOp, updateHud = noOp, showCombo = noOp, celebrate = noOp, recordDailyAction = noOp;
  function isDailyMode() { return true; }
  function finishDailyAtLimit() { state = "ended"; }
  function setRemovalMode(active) { removalMode = active; }
  function showResult() { state = coins > 0 ? "revive" : "ended"; }

${gameplay.map(func).join("\n\n")}

  function advanceTo(tick) {
    while (roundTick < tick && state === "playing") advance();
    return roundTick === tick;
  }
  for (const action of actions) {
    if (!Array.isArray(action) || action.length < 2 || action.length > 3 ||
        !Number.isInteger(action[0]) || action[0] < roundTick || action[0] > finalTick ||
        !advanceTo(action[0])) return null;
    const [, kind, arg] = action;
    if (kind === "d" && action.length === 3 && state === "playing" && cooldown === 0 &&
        Number.isInteger(arg) && arg >= 0 && arg <= width * 100) {
      aim = arg / 100; drop();
    } else if (kind === "t" && action.length === 3 && state === "playing" && tickets > 0 &&
               Number.isInteger(arg) && arg >= 0 && arg < balls.length) {
      setRemovalMode(true); removePiece(balls[arg]);
    } else if (kind === "r" && action.length === 2 && state === "revive") {
      revive();
    } else if (kind === "f" && action.length === 2 && state === "revive") {
      state = "ended";
    } else {
      return null;
    }
  }
  if (!advanceTo(finalTick) || state !== "ended") return null;
  return { score, drops };
}
`;
writeFileSync(new URL("engine.mjs", import.meta.url),code);
